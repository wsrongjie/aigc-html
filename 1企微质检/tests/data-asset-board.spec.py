"""在隔离 Chromium 中验证数据资产看板、接口快照配置与模拟健康状态。"""
import functools
import json
import os
from pathlib import Path
import sys
import threading
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from playwright.sync_api import sync_playwright, expect

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'outputs/data-asset-board'
HTML = '数据资产交互设计.html'

class QuietHandler(SimpleHTTPRequestHandler):
    def log_message(self, *_args):
        pass

def main():
    sys.stdout.reconfigure(encoding='utf-8')
    os.environ.setdefault('PLAYWRIGHT_BROWSERS_PATH', str(Path.home() / 'AppData/Local/ms-playwright'))
    report = {'checks': [], 'errors': [], 'externalRequests': [], 'layouts': []}
    def check(name, value=True):
        assert value, name
        report['checks'].append(name)
        print('通过：' + name, flush=True)
    server = ThreadingHTTPServer(('127.0.0.1', 0), functools.partial(QuietHandler, directory=str(ROOT)))
    threading.Thread(target=server.serve_forever, daemon=True).start()
    try:
        with sync_playwright() as pw:
            browser = pw.chromium.launch(headless=True)
            context = browser.new_context(viewport={'width': 1440, 'height': 1050}, reduced_motion='reduce', accept_downloads=True)
            page = context.new_page()
            page.on('pageerror', lambda e: report['errors'].append(str(e)))
            page.on('request', lambda r: report['externalRequests'].append(r.url) if r.url.startswith('http') and '127.0.0.1' not in r.url else None)
            page.goto(f'http://127.0.0.1:{server.server_port}/{HTML}')
            page.wait_for_function('window.assetDemoReady === true')
            expect(page.locator('#data-asset-board')).to_be_visible()
            model = lambda: page.evaluate('DataAssetBoard.getModel()')
            m = model()
            report['initial'] = {k: len(m[k]) for k in ['records','added','covered','sales','high','pending','overdue','missingContracts']}
            independent = page.evaluate('''()=>{const d=AssetDemo.getData();return {records:d.assets.filter(a=>a.type!=='conversation'&&!a.uploaded).length+d.messages.length+d.liveActions.length+d.reviews.length,sales:['e1','e2','e3']};}''')
            check('归集总数按资产、消息、动作和审核独立核对', len(m['records']) == independent['records'])
            check('分类合计与记录 ID 唯一', sum(c['total'] for c in m['categories']) == len(m['records']) == len(set(r['id'] for r in m['records'])))
            expected_covered = sorted({cid for r in m['records'] for cid in r['customerIds']})
            check('覆盖人数按稳定 ID 去重，排除目录占位及投研作者', sorted(m['covered']) == expected_covered and sorted(m['sales']) == independent['sales'])
            check('演示风险等级与处置状态独立', {r['id'] for r in m['high']} == {'c3','c5'} and len(m['unassigned']) == 1)
            check('缺截止时间不误判超期，购买合同按订单关联', len(m['overdue']) == 0 and 'rf1' in {r['id'] for r in m['unknownDue']} and all(r['id'] not in {'o1','o2','o3'} for r in m['missingContracts']) and {r['id'] for r in m['missingContracts']} == {'o4','o5'})
            teams=[r for r in m['dimensions']['team'] if r['ids']]
            union=set().union(*[set(r['ids']) for r in teams])
            check('团队按实际对接关系统计，不通过共享素材串联客户', len(teams)==2 and union <= set(m['covered']) and len(union) >= 6)
            d=m['deal']; st={x['key']:x['count'] for x in d['statuses']}
            check('成交口径自洽：已支付+退款中+已退款=本期成交笔数', st.get('已支付',0)+st.get('退款中',0)+st.get('已退款',0)==d['count'])
            check('未成交口径自洽：待支付+已取消+支付失败=未成交笔数', st.get('待支付',0)+st.get('已取消',0)+st.get('支付失败',0)==d['lostCount'])
            check('成交金额与逐日趋势合计一致', sum(r['amount'] for r in d['trend'])==d['amount'] and sum(r['count'] for r in d['trend'])==d['count'])
            check('退款金额与逐日趋势合计一致', sum(r['refund'] for r in d['trend'])==d['refundAmount'] and sum(r['refundCount'] for r in d['trend'])==d['refundCount'])
            check('净额与退款率计算正确', d['net']==d['amount']-d['refundAmount'] and abs(float(d['refundRate'].rstrip('%'))/100-d['refundAmount']/d['amount'])<0.001)
            check('商品成交金额合计等于成交金额', sum(p['amount'] for p in d['products'])==d['amount'])
            check('未成交原因笔数不超过未成交总数', sum(x['count'] for x in d['lostReasons'])<=d['lostCount'])
            check('本期新增客户为覆盖客户子集，其中成交为客户子集', set(d['newCustomers'])<=set(m['covered']) and set(d['newDealCustomers'])<=set(d['newCustomers']) and len(d['newDealCustomers'])>0)
            page.evaluate('DataAssetBoard.openList("deal-new-customers")')
            expect(page.locator('#board-detail-title .count')).to_have_text(str(len(d['newCustomers'])))
            page.keyboard.press('Escape')
            check('本期新增客户可下钻且数量一致')
            check('退款订单数与退款原因笔数一致', sum(x['n'] for x in d['refundReasons'])==d['refundCount'])
            check('退款原因均在客户侧原因清单内', {x['label'] for x in d['refundReasons']} <= {'服务后亏损过多','前期夸大营销','服务不到位','内容质量不达预期','重复购买或误购','服务期限与条款理解不一致','客户资金安排变化'})
            check('退款跟进只包含未完成退款', all(x['tag']=='退款中' for x in d['followups']))
            for key in ['deal-paid','deal-lost','deal-refund','deal-follow']:
                page.evaluate('(k)=>DataAssetBoard.openList(k)', key)
                expect(page.locator('#board-detail-title .count')).to_have_count(1)
                page.keyboard.press('Escape')
            check('成交与退款指标可下钻')
            check('期间每日新增合计一致', sum(r['added'] for r in m['trend']) == len(m['added']))
            check('风险趋势末值与当前指标一致', m['trend'][-1]['high'] == len(m['high']))
            for key, group in m['lists'].items():
                page.evaluate('(key)=>DataAssetBoard.openList(key)', key)
                expect(page.locator('#board-detail-title .count')).to_have_text(str(len(group['rows'])))
                page.keyboard.press('Escape')
            check('全部指标与分类下钻数量一致')
            page.evaluate('DataAssetBoard.openList("records")')
            expect(page.locator('#board-detail .dab-record')).to_have_count(20)
            page.locator('[data-action="board-list-page"][data-id="1"]').click()
            with page.expect_download() as info:
                page.locator('[data-action="board-list-export"]').click()
            exported = json.loads(Path(info.value.path()).read_text(encoding='utf-8'))
            check('分页不改变导出范围', len(exported['rows']) == len(m['records']))
            page.keyboard.press('Escape')
            page.locator('[data-action="board-range"][data-id="30"]').click()
            m30 = model()
            check('30 日切换只改变期间指标', len(m30['added']) >= len(m['added']) and len(m30['trend']) == 30 and all(len(m[k]) == len(m30[k]) for k in ['records','covered','sales','high','pending','overdue']))
            check('30 日成交与退款笔数不小于 7 日', m30['deal']['count'] >= m['deal']['count'] and m30['deal']['refundCount'] >= m['deal']['refundCount'] and len(m30['deal']['newCustomers']) >= len(m['deal']['newCustomers']))
            page.locator('[data-action="board-range"][data-id="7"]').click()
            for dim in ['product','channel','team']:
                page.evaluate('(d)=>{AssetDemo.setState?null:null;DataAssetBoard.openList("category:order");}', dim)
                page.keyboard.press('Escape')
            check('成交口径下保留团队、产品、渠道维度计算')
            with page.expect_download() as info:
                page.locator('#main [data-action="export"]').click()
            board_export = json.loads(Path(info.value.path()).read_text(encoding='utf-8'))
            check('首页导出保留期间及同源明细', board_export['records']['start']==m['start'] and len(board_export['records']['records'])==len(m['records']))
            page.evaluate('DataAssetBoard.openList("category:message")')
            page.locator('#board-detail [data-action="board-record"]').first.click()
            expect(page.locator('#detail .message.located')).to_have_count(1)
            page.keyboard.press('Escape')
            check('消息下钻定位原始消息')
            page.evaluate('DataAssetBoard.openList("category:review")')
            page.locator('#board-detail [data-action="board-record"]').first.click()
            expect(page.locator('#detail')).to_be_visible()
            check('审核下钻保留对应版本', page.evaluate('AssetDemo.getState().drawer.tab') == 'reviews')
            page.keyboard.press('Escape')
            page.evaluate('DataAssetBoard.openList("high")')
            page.locator('#board-detail [data-key="profile"]').first.click()
            expect(page.locator('#customer-record-timeline')).to_be_visible()
            page.locator('#customer-profile-back').click()
            expect(page.locator('#data-asset-board')).to_be_visible()
            check('客户档案下钻可返回看板')
            for width in [1440,1024,768,390]:
                page.set_viewport_size({'width':width,'height':1050})
                page.evaluate('AssetDemo.nav("board")')
                layout = page.evaluate('''()=>({overflow:document.documentElement.scrollWidth>innerWidth,panelOverflow:[...document.querySelectorAll('#data-asset-board .panel')].some(n=>n.scrollWidth>n.clientWidth+1)})''')
                check(f'{width}px 看板无页面和面板溢出', not layout['overflow'] and not layout['panelOverflow'])
                report['layouts'].append({'width':width,'page':'board',**layout})
                if width in [1440,390]:
                    page.screenshot(path=str(OUT/f'board-{width}.png'),full_page=True)
                page.evaluate('AssetDemo.nav("sources")')
                expect(page.locator('.dab-source-card')).to_have_count(6)
                check(f'{width}px 来源页无横向溢出', page.evaluate('document.documentElement.scrollWidth<=innerWidth'))
                if width in [1440,390]:
                    page.screenshot(path=str(OUT/f'sources-{width}.png'),full_page=True)
            check('移除待关联资料展示与主动上传', '待关联资料' not in page.locator('#main').inner_text() and page.locator('[data-action="upload"]').count()==0 and 'upload' not in page.evaluate('AssetDemo.getData().sources.map(s=>s.id)'))
            page.set_viewport_size({'width':1440,'height':1050})
            page.locator('[data-action="source-config"][data-id="wecom"]').click()
            form = page.locator('#source-config-form')
            form.locator('[name="endpoint"]').fill('http://example.invalid/api')
            form.locator('[name="tenant"]').fill('tenant-demo')
            form.locator('[name="secret"]').fill('demo-secret-not-persisted')
            form.locator('[type="submit"]').click()
            expect(page.locator('#source-config-error')).to_contain_text('HTTPS')
            form.locator('[name="endpoint"]').fill('https://example.invalid/api?token=bad')
            form.locator('[type="submit"]').click()
            expect(page.locator('#source-config-error')).to_contain_text('查询参数')
            form.locator('[name="endpoint"]').fill('https://example.invalid/api')
            form.locator('[name="interval"]').select_option('15')
            form.locator('[type="submit"]').click()
            expect(page.locator('#source-dialog')).not_to_be_visible()
            cfg = page.evaluate('SourceSyncDemo.getConfig("wecom")')
            check('接口配置保存并默认待检测', cfg['configured'] and cfg['interval']==15 and cfg['health']=='待检测')
            stored = page.evaluate('localStorage.getItem(SourceSyncDemo.storageKey)')
            check('认证凭据不写入本地存储', 'demo-secret' not in stored)
            page.locator('[data-action="source-run"][data-id="wecom"]').click()
            page.locator('[data-action="source-check"]').click()
            expect(page.locator('#source-run-result')).to_contain_text('模拟成功')
            check('连接成功不等于同步正常', page.evaluate('SourceSyncDemo.getConfig("wecom").health') == '待检测')
            before = model()
            page.locator('[data-action="source-sync"]').click()
            cfg = page.evaluate('SourceSyncDemo.getConfig("wecom")')
            check('同步成功记录快照和水位', cfg['health']=='模拟正常' and cfg['snapshotId'] and cfg['watermark'])
            previous = cfg['snapshotId']
            page.locator('[data-action="source-sync"]').click()
            check('重复拉取不重复增加资产', len(model()['records']) == len(before['records']))
            saved_success = page.evaluate('SourceSyncDemo.getConfig("wecom").snapshotId')
            page.locator('#source-scenario').select_option('timeout')
            page.locator('[data-action="source-sync"]').click()
            cfg = page.evaluate('SourceSyncDemo.getConfig("wecom")')
            check('失败保留上次成功快照，记录重试结果', cfg['health']=='模拟异常' and cfg['snapshotId']==saved_success and cfg['logs'][0]['attempts']==4)
            page.locator('[data-action="source-close"]').click()
            page.locator('[data-action="source-toggle"][data-id="wecom"]').click()
            expect(page.locator('[data-action="source-run"][data-id="wecom"]')).to_be_disabled()
            check('暂停后同步操作禁用', not page.evaluate('SourceSyncDemo.getConfig("wecom").enabled'))
            page.locator('[data-action="source-toggle"][data-id="wecom"]').click()
            page.locator('#main [data-action="source-logs"][data-id="wecom"]').click()
            expect(page.locator('.dab-log')).to_have_count(4)
            with page.expect_download() as info:
                page.locator('[data-action="source-log-export"]').click()
            logs = Path(info.value.path()).read_text(encoding='utf-8')
            check('日志可导出且不包含凭据', 'demo-secret' not in logs and '连接超时' in logs)
            page.keyboard.press('Escape')
            page.reload()
            page.wait_for_function('window.assetDemoReady === true')
            check('刷新恢复配置与日志', len(page.evaluate('SourceSyncDemo.getConfig("wecom").logs'))==4)
            page.evaluate('AssetDemo.nav("sources")')
            page.locator('[data-action="source-run"][data-id="wecom"]').click()
            page.locator('[data-action="source-sync"]').click()
            expect(page.locator('#source-run-result')).to_contain_text('缺少认证凭据')
            check('刷新后凭据不残留，不伪报认证成功')
            page.keyboard.press('Escape')
            page.locator('[data-action="source-config"][data-id="wecom"]').click()
            page.locator('[name="secret"]').fill('new-demo-secret')
            page.locator('#source-config-form [type="submit"]').click()
            page.locator('[data-action="source-run"][data-id="wecom"]').click()
            page.locator('[data-action="source-sync"]').click()
            check('补充凭据后同步恢复', page.evaluate('SourceSyncDemo.getConfig("wecom").health')=='模拟正常')
            page.screenshot(path=str(OUT/'sync-success.png'),full_page=True)
            page.locator('#source-scenario').select_option('auth')
            page.locator('[data-action="source-check"]').click()
            check('最新连接失败反映到健康状态', page.locator('[data-source-id="wecom"] > .between').inner_text().endswith('连接异常'))
            page.keyboard.press('Escape')
            old_logs = len(page.evaluate('SourceSyncDemo.getConfig("wecom").logs'))
            page.locator('#main [data-action="source-config"][data-id="wecom"]').click()
            page.locator('[name="cursor"]').fill('modified_at')
            page.set_viewport_size({'width':390,'height':844})
            check('390px 接口配置抽屉无横向溢出', page.locator('#source-dialog').evaluate('n=>n.scrollWidth<=n.clientWidth && document.documentElement.scrollWidth<=innerWidth'))
            page.screenshot(path=str(OUT/'source-config-390.png'),full_page=True)
            page.locator('#source-config-form [type="submit"]').click()
            cfg = page.evaluate('SourceSyncDemo.getConfig("wecom")')
            check('增量字段变更重置水位且保留历史日志', cfg['watermark'] is None and cfg['snapshotId'] is None and len(cfg['logs'])==old_logs and cfg['health']=='待检测')
            # 模拟外部来源的异常时间，验证固定快照不会混入未来状态。
            edge = page.evaluate('''()=>{const d=AssetDemo.getData(),r=d.assets.find(a=>a.id==='rf1'),saved={...r};r.time='2026-10-26 12:00:00';const future=DataAssetBoard.getModel().records.some(x=>x.assetId==='rf1');Object.assign(r,saved);d.messages[0].ingestedAt='invalid';const invalid=DataAssetBoard.getModel().records.some(x=>x.messageId===d.messages[0].id);delete d.messages[0].ingestedAt;return {future,invalid};}''')
            check('未来来源状态和无效归集时间不混入快照', not edge['future'] and not edge['invalid'])
            # 空数据仅在隔离内存中改变，不写入原型或用户数据。
            page.evaluate('''()=>{const d=AssetDemo.getData();d.assets.splice(0);d.messages.splice(0);d.liveActions.splice(0);d.reviews.splice(0);Object.keys(businessHistory).forEach(k=>delete businessHistory[k]);Object.keys(productHistory).forEach(k=>delete productHistory[k]);AssetDemo.nav('board');}''')
            check('空数据看板稳定，无 NaN 或 Infinity', len(model()['records'])==0 and 'NaN' not in page.locator('#main').inner_text() and 'Infinity' not in page.locator('#main').inner_text())
            check('原型未发起任何真实后台请求', not report['externalRequests'])
            check('无页面脚本错误', not report['errors'])
            direct = context.new_page()
            direct.goto((ROOT/HTML).as_uri())
            direct.wait_for_function('window.assetDemoReady === true')
            expect(direct.locator('#data-asset-board')).to_be_visible()
            direct.evaluate('AssetDemo.nav("sources")')
            expect(direct.locator('.dab-source-card')).to_have_count(6)
            check('直接打开本地 HTML 可查看首页及数据来源')
            direct.close()
            (OUT/'report.json').write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding='utf-8')
            browser.close()
    finally:
        server.shutdown()

if __name__ == '__main__':
    main()
